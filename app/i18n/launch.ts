export const launch: Record<"en" | "pt" | "es", Launch> = { en, pt, es };

/** The visitor-facing sentence for an API error body, in their language. */
export function apiErrorText(body: unknown, l: Launch, fallback: string): string {
  const code = (body as { error?: unknown } | null)?.error;
  return typeof code === "string" && code in l.apiErrors ? l.apiErrors[code as keyof Launch["apiErrors"]] : fallback;
}
